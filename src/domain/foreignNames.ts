/** 出身地と候補の id から、外国人らしい名前を決める（同じ入力なら必ず同じ名前） */
export function foreignName(from: string, key: string): string {
  const pool = POOLS[from] ?? POOLS['アメリカ'];
  const seed = seedFrom(`foreign-name-v1:${key}`);
  const given = pool.given[seed % pool.given.length];
  const family = pool.family[Math.floor(seed / 97) % pool.family.length];
  return pool.order === 'given-family' ? `${given}${pool.sep}${family}` : `${family}${pool.sep}${given}`;
}

/** 日本人の名前の形（「姓 名」の空白区切り・かな読み）のままになっている助っ人か */
export function needsForeignName(name: string, from: string): boolean {
  if (from === '台湾') return !/^[陳林黄張李王呉劉蔡楊許鄭謝郭洪邱] /.test(name);
  return !name.includes('・');
}
